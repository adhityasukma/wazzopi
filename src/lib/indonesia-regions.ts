/**
 * Mencari kode pos default wilayah kota/kabupaten
 */
export function findPostalCodeByCity(cityName: string, provinceName?: string): string | null {
  if (!cityName) return null;
  const clean = cityName.trim().toLowerCase();

  // 1. Cocokkan langsung
  if (CITY_POSTAL_CODES[clean]) return CITY_POSTAL_CODES[clean];

  // 2. Cocokkan tanpa awalan Kab./Kota
  const stripped = clean.replace(/^(kab\.|kota)\s+/, "").trim();
  if (CITY_POSTAL_CODES[stripped]) return CITY_POSTAL_CODES[stripped];

  // 3. Cocokkan substring pada daftar kunci
  for (const [key, code] of Object.entries(CITY_POSTAL_CODES)) {
    if (key.includes(stripped) || stripped.includes(key)) {
      return code;
    }
  }

  // 4. Fallback ke kode pos ibu kota provinsi jika provinsi diketahui
  const province = provinceName || findProvinceByCity(cityName);
  if (province && PROVINCE_DEFAULT_POSTAL[province]) {
    return PROVINCE_DEFAULT_POSTAL[province];
  }

  return null;
}
