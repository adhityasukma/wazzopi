/**
 * Mencari kota/kabupaten berdasarkan kata kunci (pencarian fuzzy / substring)
 */
export function searchIndonesianRegions(query: string, limit = 15): IndonesianRegion[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return [];

  const startsWithMatches: IndonesianRegion[] = [];
  const containsMatches: IndonesianRegion[] = [];

  for (const item of INDONESIAN_REGIONS) {
    const cityNameLower = item.city.toLowerCase();
    const provinceLower = item.province.toLowerCase();

    // Prioritaskan nama kota yang diawali query (atau tanpa awalan "Kab. " / "Kota ")
    const strippedCity = cityNameLower.replace(/^(kab\.|kota)\s+/, "");

    if (strippedCity.startsWith(clean) || cityNameLower.startsWith(clean)) {
      startsWithMatches.push(item);
    } else if (cityNameLower.includes(clean) || provinceLower.includes(clean)) {
      containsMatches.push(item);
    }

    if (startsWithMatches.length >= limit) break;
  }

  return [...startsWithMatches, ...containsMatches].slice(0, limit);
}

/**
 * Mencari provinsi berdasarkan nama kota/kabupaten yang sudah tersimpan
 */
export function findProvinceByCity(cityName: string): string | null {
  if (!cityName) return null;
  const clean = cityName.trim().toLowerCase();

  const exact = INDONESIAN_REGIONS.find((r) => r.city.toLowerCase() === clean);
  if (exact) return exact.province;

  // Coba cari kecocokan sebagian tanpa "Kab." / "Kota"
  const stripped = clean.replace(/^(kab\.|kota)\s+/, "");
  const partial = INDONESIAN_REGIONS.find((r) => {
    const s = r.city.toLowerCase().replace(/^(kab\.|kota)\s+/, "");
    return s === stripped || s.includes(stripped) || stripped.includes(s);
  });

  return partial ? partial.province : null;
}
